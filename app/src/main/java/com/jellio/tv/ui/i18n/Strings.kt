    fun get(key: String, lang: AppLanguage = DisplayPreferences.displayLanguage): String {
        val dict = when (lang) {
            AppLanguage.GERMAN -> DE
            AppLanguage.SPANISH -> ES
            AppLanguage.POLISH -> PL
            AppLanguage.ENGLISH -> EN
        }
        return dict[key] ?: EN[key] ?: key
    }

    fun format(key: String, vararg args: Any, lang: AppLanguage = DisplayPreferences.displayLanguage): String {
        val raw = get(key, lang)
        return try {
            String.format(raw, *args)
        } catch (_: Exception) {
            raw
        }
    }
}

@Composable
fun string(key: String): String = Strings.get(key, DisplayPreferences.displayLanguage)

@Composable
fun formatString(key: String, vararg args: Any): String =
    Strings.format(key, *args, lang = DisplayPreferences.displayLanguage)
